"""Copy the Medi-Bela app's public text (About us, Privacy & terms, contact numbers) into
src/content/app-public.ts, word for word, so the website and the app say the same thing.

    python scripts/sync-app-content.py [path/to/Medi-Bela/docs/content/public-pages.json]

Default source: ../Medi-Bela/docs/content/public-pages.json. Run again whenever the app's
text changes. Team photos are copied separately into public/assets/team/.
The app's Support "how to" text is NOT copied: it still says Later = 30 min, twice at most,
which contradicts the app's CLAUDE.md (15 min rings); see CONTENT_NOTES.md.
"""
import json
import sys
from pathlib import Path

src = Path(sys.argv[1] if len(sys.argv) > 1 else '../Medi-Bela/docs/content/public-pages.json')
data = json.loads(src.read_text(encoding='utf-8'))

KEYS = ['privacyTitle', 'privacySections', 'aboutTitle', 'missionLabel', 'mission', 'visionLabel', 'vision',
        'goalsHeading', 'goals', 'teamHeading', 'facebookLabel', 'team', 'contactHeading', 'callLabel',
        'whatsappLabel']

out = {lang: {k: data[lang][k] for k in KEYS} for lang in ('en', 'bn')}
for lang in out:
    for member in out[lang]['team']:
        member['photo'] = '/assets/team/' + member['photo']
contacts = data['contacts']

ts = (
    '// GENERATED by scripts/sync-app-content.py from the Medi-Bela app\'s\n'
    '// docs/content/public-pages.json. Do not edit by hand: change the app\'s file and re-run.\n'
    '// REVIEW: Bangla text is the app\'s own; review it there.\n\n'
    f'export const appPublic = {json.dumps(out, ensure_ascii=False, indent=2)} as const\n\n'
    f'export const appContacts = {json.dumps(contacts, ensure_ascii=False, indent=2)} as const\n'
)
dest = Path('src/content/app-public.ts')
dest.write_text(ts, encoding='utf-8')
print(f'wrote {dest} from {src}')
